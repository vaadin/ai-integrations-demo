-- The seeded dashboards: every visit opens Insights with two to five widgets for each demo user, to look at and to
-- refine. What a visitor saves stays with their session, so these rows are only read. The dataset creates
-- saved_widgets and seeds Test User's first two (ids 1 and 2); this script adds the widgets' chats and the rest.
-- The queries name no country: the scoped views apply the signed-in user's region when they run.
-- state_json holds what differs from a widget's defaults: a table is two columns wide, so that its columns show, and
-- a chart names its kind; a chart without a saved look is drawn as columns. A dashboard is laid out in rows of three
-- with the New Query tile last, so a wide table starts a row.

-- The chat behind each seeded widget, oldest first, as the orchestrator keeps it: a reply keeps the model's title
-- and summary lines, which the chat does not show. The times are wall-clock times on the dataset's day, read in the
-- visitor's time zone.
CREATE TABLE saved_widget_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    widget_id INT NOT NULL REFERENCES saved_widgets (id),
    position INT NOT NULL,
    role VARCHAR(10) NOT NULL,
    content CLOB NOT NULL,
    sent_at TIMESTAMP NOT NULL
);
CREATE INDEX saved_widget_messages_widget ON saved_widget_messages (widget_id, position);

-- The dataset's "Claims open for over 7 days" counts from CURRENT_TIMESTAMP, the database server's clock, which the
-- dataset's own schema text tells the model never to use; counted from the dataset's day, the widget shows the same
-- claims whenever the demo runs. Its table is two columns wide, like the tables below.
UPDATE saved_widgets
SET query_sql = REPLACE(query_sql, 'CURRENT_TIMESTAMP', 'DATE ''2026-09-07''')
WHERE query_sql LIKE '%CURRENT_TIMESTAMP%';
UPDATE saved_widgets SET state_json = '{"colspan":2}' WHERE widget_type = 'GRID' AND state_json IS NULL;

